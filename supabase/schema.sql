CREATE INDEX IF NOT EXISTS sessions_by_user ON sessions(user_id, stage);
CREATE INDEX IF NOT EXISTS attempts_by_name_time ON login_attempts(username, attempted_at);
CREATE INDEX IF NOT EXISTS audit_by_time ON audit_events(created_at);
CREATE INDEX IF NOT EXISTS books_by_title ON books(title);
CREATE INDEX IF NOT EXISTS members_by_name ON library_members(full_name);
CREATE INDEX IF NOT EXISTS loans_by_due_date ON loans(due_at) WHERE returned_at IS NULL;
CREATE INDEX IF NOT EXISTS loans_by_member ON loans(member_id, returned_at);
CREATE INDEX IF NOT EXISTS config_snapshots_by_created ON system_config_snapshots(created_at DESC);

